//! Tunnel System Doctor & Kernel Network Performance Tuner (`src/ops_suite.rs`).
//!
//! Pure tunneling diagnostics & kernel tuning subsystem:
//!   * **Tunnel Doctor (`run_full_diagnostics`)**: audits `ip_forward`, `rp_filter`,
//!     `tcp_congestion_control`, `default_qdisc`, and `tcp_mtu_probing`, emitting a
//!     structured `DoctorReport` (`PASS` | `WARN` | `FAIL`) with actionable fix hints.
//!   * **Kernel Perf Tuner (`PerfConfig`)**: configures TCP BBR, `fq` qdisc, 16 MiB socket
//!     buffers, `somaxconn = 8192`, `tcp_fastopen = 3`, `tcp_slow_start_after_idle = 0`,
//!     `tcp_mtu_probing = 1`, `ip_forward = 1`, and `rp_filter = 0` for asymmetric tunnels.

use crate::hjson::{self, Json};
use crate::sysrun;
use crate::util::now_unix;
use anyhow::Result;

#[derive(Clone, Debug)]
pub struct PerfConfig {
    pub enable_bbr: bool,
    pub qdisc: String, // "fq" | "fq_codel"
    pub rmem_max: u64,
    pub wmem_max: u64,
    pub somaxconn: u32,
    pub tcp_mtu_probing: u8,
    pub ip_forward: bool,
    pub backhaul_pool: u32,
}

impl Default for PerfConfig {
    fn default() -> Self {
        Self {
            enable_bbr: true,
            qdisc: "fq".into(),
            rmem_max: 16 * 1024 * 1024,
            wmem_max: 16 * 1024 * 1024,
            somaxconn: 8192,
            tcp_mtu_probing: 1,
            ip_forward: true,
            backhaul_pool: 8,
        }
    }
}

impl PerfConfig {
    pub fn sysctl_pairs(&self) -> Vec<(&'static str, String)> {
        let mut p = vec![
            ("net.core.default_qdisc", self.qdisc.clone()),
            ("net.core.rmem_max", self.rmem_max.to_string()),
            ("net.core.wmem_max", self.wmem_max.to_string()),
            ("net.core.somaxconn", self.somaxconn.to_string()),
            ("net.ipv4.tcp_mtu_probing", self.tcp_mtu_probing.to_string()),
            ("net.ipv4.tcp_fastopen", "3".into()),
            ("net.ipv4.tcp_slow_start_after_idle", "0".into()),
            ("net.ipv4.ip_forward", if self.ip_forward { "1" } else { "0" }.into()),
            ("net.ipv4.conf.all.rp_filter", "0".into()),
            ("net.ipv4.conf.default.rp_filter", "0".into()),
        ];
        if self.enable_bbr {
            p.push(("net.ipv4.tcp_congestion_control", "bbr".into()));
        }
        p
    }

    pub fn render_sysctl_conf(&self) -> String {
        let mut s = String::from("# Generated by Khaymali Tunnel Kernel Perf Tuner\n");
        for (k, v) in self.sysctl_pairs() {
            s.push_str(&format!("{k} = {v}\n"));
        }
        s
    }

    pub fn apply(&self, sysctl_conf_path: &str) -> Result<usize> {
        let conf = self.render_sysctl_conf();
        if sysrun::is_dry_run() {
            let _ = sysrun::run(&crate::v!["write-file", sysctl_conf_path, format!("{}B", conf.len())]);
        } else {
            hjson::write_atomic(sysctl_conf_path, conf.as_bytes())?;
        }
        let mut applied = 0;
        for (k, v) in self.sysctl_pairs() {
            let o = sysrun::run(&crate::v!["sysctl", "-w", format!("{k}={v}")]);
            if o.ok {
                applied += 1;
            }
        }
        Ok(applied)
    }

    pub fn save(&self, path: &str) -> Result<()> {
        let j = Json::obj()
            .set("enable_bbr", self.enable_bbr)
            .set("qdisc", self.qdisc.clone())
            .set("rmem_max", self.rmem_max)
            .set("wmem_max", self.wmem_max)
            .set("somaxconn", self.somaxconn)
            .set("tcp_mtu_probing", self.tcp_mtu_probing as u64)
            .set("ip_forward", self.ip_forward)
            .set("backhaul_pool", self.backhaul_pool);
        hjson::write_atomic(path, j.to_string_pretty().as_bytes())
    }
}

#[derive(Clone, Debug)]
pub struct DoctorFinding {
    pub severity: String, // "ok" | "warn" | "fail"
    pub category: String,
    pub message: String,
    pub fix_hint: String,
}

#[derive(Clone, Debug)]
pub struct KernelAudit {
    pub ip_forward: String,
    pub rp_filter: String,
    pub congestion_control: String,
    pub default_qdisc: String,
    pub mtu_probing: String,
}

#[derive(Clone, Debug)]
pub struct DoctorReport {
    pub generated_unix: u64,
    pub overall: String, // "PASS" | "WARN" | "FAIL"
    pub kernel: KernelAudit,
    pub findings: Vec<DoctorFinding>,
}

impl DoctorReport {
    pub fn to_json(&self) -> Json {
        let f_arr: Vec<Json> = self
            .findings
            .iter()
            .map(|f| {
                Json::obj()
                    .set("severity", f.severity.clone())
                    .set("category", f.category.clone())
                    .set("message", f.message.clone())
                    .set("fix_hint", f.fix_hint.clone())
            })
            .collect();
        Json::obj()
            .set("generated_unix", self.generated_unix)
            .set("overall", self.overall.clone())
            .set(
                "kernel",
                Json::obj()
                    .set("ip_forward", self.kernel.ip_forward.clone())
                    .set("rp_filter", self.kernel.rp_filter.clone())
                    .set("congestion_control", self.kernel.congestion_control.clone())
                    .set("default_qdisc", self.kernel.default_qdisc.clone())
                    .set("mtu_probing", self.kernel.mtu_probing.clone()),
            )
            .set("findings", f_arr)
    }
}

fn read_sysctl(key: &str) -> String {
    if sysrun::is_dry_run() {
        return match key {
            "net.ipv4.ip_forward" => "1".into(),
            "net.ipv4.conf.all.rp_filter" => "0".into(),
            "net.ipv4.tcp_congestion_control" => "bbr".into(),
            "net.core.default_qdisc" => "fq".into(),
            "net.ipv4.tcp_mtu_probing" => "1".into(),
            _ => String::new(),
        };
    }
    let proc_path = format!("/proc/sys/{}", key.replace('.', "/"));
    std::fs::read_to_string(proc_path)
        .map(|s| s.trim().to_string())
        .unwrap_or_default()
}

/// Runs Khaymali's full kernel and network tunnel readiness audit.
pub fn run_full_diagnostics() -> DoctorReport {
    let kernel = KernelAudit {
        ip_forward: read_sysctl("net.ipv4.ip_forward"),
        rp_filter: read_sysctl("net.ipv4.conf.all.rp_filter"),
        congestion_control: read_sysctl("net.ipv4.tcp_congestion_control"),
        default_qdisc: read_sysctl("net.core.default_qdisc"),
        mtu_probing: read_sysctl("net.ipv4.tcp_mtu_probing"),
    };
    let mut findings = Vec::new();
    if kernel.ip_forward != "1" {
        findings.push(DoctorFinding {
            severity: "fail".into(),
            category: "kernel".into(),
            message: format!("net.ipv4.ip_forward={} (forwarding disabled)", kernel.ip_forward),
            fix_hint: "run `khaymali ops tune --apply`".into(),
        });
    } else {
        findings.push(DoctorFinding {
            severity: "ok".into(),
            category: "kernel".into(),
            message: "IPv4 forwarding enabled".into(),
            fix_hint: String::new(),
        });
    }
    if kernel.congestion_control != "bbr" {
        findings.push(DoctorFinding {
            severity: "warn".into(),
            category: "perf".into(),
            message: format!("TCP congestion control is '{}' instead of 'bbr'", kernel.congestion_control),
            fix_hint: "run `khaymali ops tune --apply` to enable BBR + fq".into(),
        });
    } else {
        findings.push(DoctorFinding {
            severity: "ok".into(),
            category: "perf".into(),
            message: format!("TCP BBR active with qdisc '{}'", kernel.default_qdisc),
            fix_hint: String::new(),
        });
    }
    if kernel.rp_filter == "1" {
        findings.push(DoctorFinding {
            severity: "warn".into(),
            category: "routing".into(),
            message: "strict rp_filter=1 can drop asymmetric GRE/Spoof tunnel packets".into(),
            fix_hint: "set net.ipv4.conf.all.rp_filter=0".into(),
        });
    }
    if kernel.mtu_probing == "0" {
        findings.push(DoctorFinding {
            severity: "warn".into(),
            category: "mtu".into(),
            message: "tcp_mtu_probing=0 (blackhole PMTU detection off)".into(),
            fix_hint: "set net.ipv4.tcp_mtu_probing=1".into(),
        });
    }

    let overall = if findings.iter().any(|f| f.severity == "fail") {
        "FAIL"
    } else if findings.iter().any(|f| f.severity == "warn") {
        "WARN"
    } else {
        "PASS"
    }
    .to_string();

    DoctorReport {
        generated_unix: now_unix(),
        overall,
        kernel,
        findings,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn perf_tuner_and_tunnel_doctor() {
        sysrun::set_dry_run(true);
        let _ = sysrun::take_log();
        let perf = PerfConfig::default();
        let n = perf.apply("/etc/sysctl.d/99-khaymali.conf").unwrap();
        assert!(n >= 10);
        let rep = run_full_diagnostics();
        assert_eq!(rep.overall, "PASS");
        assert_eq!(rep.kernel.congestion_control, "bbr");
        sysrun::set_dry_run(false);
    }
}
